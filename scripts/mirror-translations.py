#!/usr/bin/env python3
"""Make every blog post exist in every site language.

    python3 scripts/mirror-translations.py          # create/refresh mirrors
    python3 scripts/mirror-translations.py --check  # exit 1 if anything is missing/stale

A post is a directory under content/blog/ with index.<lang>.md files, one per
language from [languages] in config.toml. (default_language is a hidden "und"
used only for the root home page, so every real language gets a URL prefix.) Files without `mirror_of` in [extra] are originals
(written by a human). For every language that has no original, this script
writes a mirror: the original's text plus `extra.mirror_of = "<lang>"`, so the
template can say "not translated yet". To translate a post, edit its mirror
and delete the `mirror_of` line: from then on the script leaves it alone.

It also creates the transparent `_index*.md` sections for the YYYY/MM/DD
directories, so the posts show up in /blog/ of every language.

Runs in CI before `zola build`, so a forgotten mirror never reaches the site.
"""

import re
import sys
import tomllib
from datetime import date, datetime, time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BLOG = ROOT / "content" / "blog"
FM = re.compile(r"\A\+\+\+\n(.*?)\n\+\+\+\n?(.*)\Z", re.S)
MIRROR_HEADER = "# Generated by scripts/mirror-translations.py; remove `mirror_of` to make it a real translation.\n"


def languages():
    cfg = tomllib.loads((ROOT / "config.toml").read_text(encoding="utf-8"))
    default = cfg["default_language"]
    return default, [l for l in cfg.get("languages", {}) if l != default]


def file_lang(path: Path, default: str) -> str:
    parts = path.name.split(".")
    return parts[1] if len(parts) == 3 else default


def file_for(lang: str, default: str, stem: str = "index") -> str:
    return f"{stem}.md" if lang == default else f"{stem}.{lang}.md"


def parse(path: Path):
    m = FM.match(path.read_text(encoding="utf-8"))
    if not m:
        raise SystemExit(f"{path}: no +++ front matter")
    return tomllib.loads(m.group(1)), m.group(2)


# Minimal TOML writer for the front matter shapes used here.
def tval(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, (datetime, date, time)):
        return v.isoformat().replace("+00:00", "Z")
    if isinstance(v, str):
        return '"' + v.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'
    if isinstance(v, list):
        return "[" + ", ".join(tval(x) for x in v) + "]"
    raise TypeError(type(v))


def dump(fm: dict) -> str:
    plain = [f"{k} = {tval(v)}" for k, v in fm.items() if not isinstance(v, dict)]
    tables = [
        f"\n[{k}]\n" + "\n".join(f"{kk} = {tval(vv)}" for kk, vv in v.items())
        for k, v in fm.items()
        if isinstance(v, dict)
    ]
    return "\n".join(plain) + "".join(f"\n{t}" for t in tables)


def localize_links(body: str, lang: str, src_lang: str, default: str) -> str:
    # @/path/index.md -> @/path/index.<lang>.md (every post exists in every language)
    def internal(m):
        return "@/" + m.group(1) + "/" + file_for(lang, default, m.group(2))

    body = re.sub(r"@/([^)\s]+)/(index|_index)(?:\.[a-z]{2,3})?\.md", internal, body)
    # site-absolute links: /<src_lang>/x or /x -> /<lang>/x
    body = re.sub(rf"\]\(/(?:{re.escape(src_lang)}/)?(?![a-z]{{2,3}}/)", f"](/{lang}/", body)
    return body


def mirror_text(src: Path, lang: str, default: str) -> str:
    fm, body = parse(src)
    src_lang = file_lang(src, default)
    fm.pop("aliases", None)  # old URLs redirect to the original only
    extra = fm.setdefault("extra", {})
    extra.setdefault("lang", src_lang)
    extra["mirror_of"] = src_lang
    return "+++\n" + MIRROR_HEADER + dump(fm) + "\n+++\n" + localize_links(body, lang, src_lang, default)


def plan(default, langs):
    """Yield (path, wanted_text or None to delete)."""
    posts = {p.parent for p in BLOG.rglob("index*.md")}
    for d in sorted(posts):
        files = {file_lang(p, default): p for p in d.glob("index*.md")}
        originals = {l: p for l, p in files.items() if "mirror_of" not in parse(p)[0].get("extra", {})}
        if not originals:
            for p in files.values():
                yield p, None
            continue
        src = originals.get(default) or originals[sorted(originals)[0]]
        for lang in langs:
            if lang in originals:
                continue
            yield d / file_for(lang, default), mirror_text(src, lang, default)

        # transparent date sections between blog/ and the post
        for sec in d.relative_to(BLOG).parents:
            if sec == Path("."):
                continue
            for lang in langs:
                yield BLOG / sec / file_for(lang, default, "_index"), "+++\ntransparent = true\nrender = false\n+++\n"


def main():
    check = "--check" in sys.argv
    default, langs = languages()
    changed = []
    for path, text in plan(default, langs):
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            continue
        changed.append(path)
        if check:
            continue
        if text is None:
            path.unlink()
        else:
            path.write_text(text, encoding="utf-8")
    for p in dict.fromkeys(changed):
        print(("stale: " if check else "updated: ") + str(p.relative_to(ROOT)))
    if check and changed:
        sys.exit(1)


if __name__ == "__main__":
    main()
